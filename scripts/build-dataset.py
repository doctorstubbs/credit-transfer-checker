#!/usr/bin/env python3
"""Extract the Board of Regents Master Course Articulation Matrix
(AY 2022-2023 Excel, the newest posted on laregents.edu) into
data/courses.json and src/courses-data.js.

Each matrix row is one Louisiana Common Course (LCCN). Columns are
institutions; a cell is that college's local course code for the
common course. Cells containing *** are level electives, the words
General Elective mean a general elective, and empty means no
equivalent is listed. Raw cell text is preserved.
"""
import json, re, openpyxl

SRC = 'data/sources/matrix-2022-23.xlsx'
wb = openpyxl.load_workbook(SRC, read_only=True, data_only=True)
ws = wb['Proposed Draft Matrix 22-23']
rows = list(ws.iter_rows(values_only=True))
header = rows[2]
institutions = []
for idx in range(2, 34):
    institutions.append((idx, str(header[idx]).strip()))

VERIFIED = {
    'CENL 1013': 'Verified Nov 8, 2026: Delgado catalog and English placement page tag ENGL 101 and ENGL 110 as [LCCN: CENL 1013]; UL Lafayette transfer FAQs give Delgado ENGL 1010 = UL Lafayette ENGL 101 as their worked example; Louisiana DOE Fast Forward pathways list Delgado English Composition I as ENGL 1010 under CENL 1013.',
    'CENL 1023': 'Verified Nov 8, 2026: Delgado catalog tags ENGL 102 as [LCCN: CENL 1023].',
}

COURSES = []
for r in rows[3:]:
    lccn = (str(r[0]).strip() if r[0] else '')
    if not re.match(r'^C[A-Z]{3}\s\d{4}$', lccn):
        continue
    title = (str(r[1]).strip() if r[1] else '')
    hours = int(lccn[-1])
    equiv = {}
    for idx, name in institutions:
        cell = r[idx]
        if cell is None:
            continue
        raw = str(cell).strip()
        if raw:
            equiv[name] = raw
    COURSES.append({'lccn': lccn, 'title': title, 'hours': hours,
                    'equivalents': equiv,
                    'verified': lccn in VERIFIED,
                    'verifiedNote': VERIFIED.get(lccn)})

meta = {
    'source': 'Louisiana Board of Regents, Master Course Articulation Matrix AY 2022-2023 (Excel), via laregents.edu matrix archive; statewide titles per the Louisiana Statewide Common Course Catalog AY 2025-26.',
    'institutions': [n for _, n in institutions],
    'courseCount': len(COURSES),
}
out = dict(meta); out['courses'] = COURSES
with open('data/courses.json', 'w') as f:
    json.dump(out, f, indent=1)
with open('src/courses-data.js', 'w') as f:
    f.write('// Generated by scripts/build-dataset.py from the Board of Regents matrix.\n')
    f.write('// Do not edit by hand; regenerate. Raw cells preserved in data/courses.json.\n')
    f.write('const COURSE_DATA = ' + json.dumps(out) + ';\n')
    f.write('module.exports = { COURSE_DATA };\n')
print('courses:', len(COURSES), 'institutions:', len(institutions))
row = [c for c in COURSES if c['lccn'] == 'CENL 1013'][0]
print('CENL 1013:', row['title'], '| DCC:', row['equivalents'].get('DCC'), '| ULL:', row['equivalents'].get('ULL'), '| UNO:', row['equivalents'].get('UNO'), '| LSU A&M:', row['equivalents'].get('LSU A&M'))
# find a row where ULL cell is a level elective (***)
for c in COURSES:
    u = c['equivalents'].get('ULL', '')
    if '***' in u and c['equivalents'].get('DCC'):
        print('elective example:', c['lccn'], c['title'], '| DCC:', c['equivalents']['DCC'], '| ULL:', u)
        break
